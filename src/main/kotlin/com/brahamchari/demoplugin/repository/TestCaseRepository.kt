    override fun runTestCase(
        testId: String,
        textInput: String,
        deviceId: String,
        model: AiModelData
    ): Flow<TestExecutionLog> = channelFlow {
        val testExecutionLog = TestExecutionLog(
            id = testId,
            userInput = textInput,
            startTime = System.currentTimeMillis(),
            status = TestStatus.RUNNING,
            isSaved = false
        )

        if (isTestRunning) {
            trySend(
                testExecutionLog.copy(
                    status = TestStatus.FAILED,
                    error = ExecutionError(message = "Test is already running")
                )
            )
            close(IllegalStateException("Test is already running"))
            return@channelFlow
        }

        var serviceInitStatus = true
        if (!mcpService.isServiceRunning) {
            log.info("MCP Service not running, attempting to initialize...")
            serviceInitStatus = mcpService.initializeAndStart()
        }
        if (!serviceInitStatus) {
            log.error("MCP Service unavailable")
            trySend(
                testExecutionLog.copy(
                    status = TestStatus.FAILED,
                    error = ExecutionError(message = "Request service (MCP) unavailable")
                )
            )
            close(IllegalStateException("MCP Service unavailable"))
            return@channelFlow
        }

        isTestRunning = true
        log.info("\n\n\n\nRun Test case started for input: '$textInput'\n\n\n\n")

        currentTestJob = repositoryScope.launch(Dispatchers.IO) {
            var loopError: Exception? = null
            try {
                testExecutionLog.executionResult = ExecutionResult(
                    introduction = getTestIntro(textInput, deviceId, model),
//                    introduction = getTestIntroDemo(textInput, deviceId),
                    llmUsed = model.modelName,
                    targetDeviceId = deviceId,
                    testSteps = mutableListOf()
                )
                trySend(testExecutionLog.copy())

                do {
                    val currentStepNumber = (testExecutionLog.executionResult?.testSteps?.size ?: 0) + 1
                    log.info("\n\nRunning step $currentStepNumber")

                    val mcpResponse = makeMCPCall(testExecutionLog, deviceId, 2, model)
//                    val mcpResponse = makeMCPCallDemo(testExecutionLog, deviceId)
                    testExecutionLog.executionResult?.testSteps?.add(mcpResponse)
                    testExecutionLog.status = when(mcpResponse.outcome) {
                        StepOutcome.SUCCESS -> TestStatus.PASSED
                        StepOutcome.FAILURE -> TestStatus.FAILED
                        StepOutcome.CONTINUE -> TestStatus.RUNNING
                        StepOutcome.ERROR -> {
                            val errorMessage = mcpResponse.errorMessage ?: "Error while processing step: ${mcpResponse.title}"
                            loopError = Exception(errorMessage)
                            testExecutionLog.error = ExecutionError(errorMessage)
                            TestStatus.FAILED
                        }
                    }

                    trySend(testExecutionLog.copy())
                    log.info("Emitted step $currentStepNumber ${mcpResponse.title}. FinalStatus: ${testExecutionLog.status}\n\n")
                    delay(150) // Optional delay between steps
                } while (testExecutionLog.status == TestStatus.RUNNING && isActive)

            } catch (e: CancellationException) {
                log.info("Test execution job cancelled for input: '$textInput'.")
                loopError = e
            } catch (e: Exception) {
                log.error("Exception during test execution loop for input: '$textInput'.", e)
                loopError = e
            } finally {
                log.info("Finishing test execution job for input: '$textInput'.")
                isTestRunning = false

                if (isActive) {
                    if (loopError != null && loopError !is CancellationException) {
                        testExecutionLog.status = TestStatus.FAILED
                        testExecutionLog.error = ExecutionError(loopError.message ?: "Test failed due to exception")
                    } else if (loopError is CancellationException) {
                        testExecutionLog.status = TestStatus.STOPPED
                        testExecutionLog.error = ExecutionError("Test stopped by user")
                    }
                    trySend(testExecutionLog.copy())
                    log.info("Sent final log state: ${testExecutionLog.status}")
                } else {
                    log.warn("Flow/Scope became inactive before final state could be sent.")
                }
                // Close the flow from the producer side upon completion or error
                close(loopError) // Use default close handling
            }
        }

        // Cleanup: Cancel the job if the flow collector stops collecting
        awaitClose {
            log.warn("Test execution flow closing (awaitClose).")
            isTestRunning = false // Ensure flag is reset
            if (currentTestJob?.isActive == true) {
                log.info("Cancelling active test job due to flow closure.")
                currentTestJob?.cancel(CancellationException("Flow collection stopped."))
            }
        }
    }.flowOn(Dispatchers.IO)

    override suspend fun replayTestSteps(
        replayLogId: String,
        deviceId: String,
        originalLog: TestExecutionLog,
        model: AiModelData
    ): Flow<TestExecutionLog> = flow {
        val stepsToReplay = originalLog.executionResult?.testSteps?.sortedBy { it.timestamp } ?: emptyList()
        log.info("[Replay $replayLogId] Starting replay of ${stepsToReplay.size} steps on device $deviceId")

        val userInput = if (originalLog.userInput.startsWith("[Replay]")) originalLog.userInput else "[Replay] " + originalLog.userInput

        // --- Create the NEW log object for this replay attempt ---
        val replayLog = TestExecutionLog(
            id = replayLogId, // Use the passed-in ID
            userInput = userInput, // Copy original input
            startTime = System.currentTimeMillis(),
            status = TestStatus.RUNNING, // Start in running state
            isSaved = false, // Replays aren't saved by default
            executionResult = ExecutionResult(
                introduction = "Replaying ${stepsToReplay.size} recorded step(s)...\n${originalLog.executionResult?.introduction}", // Duplicate intro?
                llmUsed = "Replay (No AI)", // Indicate no LLM used
                targetDeviceId = deviceId,
                testSteps = mutableListOf() // IMPORTANT: Use mutable list here
            ),
        )

        try {
            emit(replayLog.copy()) // Signal loading start

            var serviceInitStatus = true
            if (!mcpService.isServiceRunning) {
                log.info("MCP Service not running, attempting to initialize...")
                serviceInitStatus = mcpService.initializeAndStart()
            }
            if (!serviceInitStatus) {
                log.error("MCP Service unavailable")
                throw IllegalStateException("MCP Service unavailable")
            }

            if (stepsToReplay.isEmpty()) {
                log.warn("[Replay $replayLogId] No steps found to replay.")
                replayLog.status = TestStatus.FAILED
                replayLog.error = ExecutionError("Original test log contained no steps to replay.")
                replayLog.endTime = System.currentTimeMillis()
                emit(replayLog.copy()) // Emit final failure state
                return@flow
            }

            for ((stepIndex, originalStep) in stepsToReplay.withIndex()) {
                if (!currentCoroutineContext().isActive) break // Check for cancellation before each step
                val stepNum = stepIndex + 1

                if(originalStep.actions == null) continue

                val currentReplayStep = originalStep.copy(
                    id = UUID.randomUUID().toString(),
                    timestamp = System.currentTimeMillis(),
                    title = "Step $stepNum",
                    outcome = StepOutcome.CONTINUE,
                )

                currentReplayStep.screenshotPath = captureAndGetScreenshotPath(stepNum, deviceId)
                delay(200) // Small delay

                val currentActions = mutableListOf<Action>()
                for(action in originalStep.actions!!) {
                    currentActions.add(action)
                    currentReplayStep.actions = currentActions
                    val toolActionToExecute = action.toolInfo

                    try {
                        if (toolActionToExecute != null) {
                            val toolResult =
                                mcpService.mcpClient.callTool(toolActionToExecute.toolName, toolActionToExecute.toolArguments)

                            if (toolResult.isFailure) { throw toolResult.exceptionOrNull()!! }
                            currentReplayStep.outcome = originalStep.outcome
                            currentReplayStep.errorMessage = originalStep.errorMessage
                        }
                    } catch (e: CancellationException) {
                        log.info("[Replay $replayLogId] Cancelled during step $stepNum")
                        currentReplayStep.outcome = StepOutcome.ERROR
                        currentReplayStep.errorMessage = "Replay stopped"
                        currentReplayStep.title = "Step $stepNum: Stopped"
                        replayLog.status = TestStatus.STOPPED
                        replayLog.error = ExecutionError("Test Cancelled by User")
                        replayLog.executionResult?.testSteps?.add(currentReplayStep)
                        throw e
                    } catch (e: Exception) {
                        log.error("[Replay $replayLogId] Failed step $stepNum: ${e.message}", e)
                        currentReplayStep.outcome = StepOutcome.FAILURE
                        currentReplayStep.errorMessage = e.message ?: "Step execution failed"
                        currentReplayStep.title = "Step $stepNum: Failed"
                        replayLog.status = TestStatus.FAILED
                        replayLog.error = ExecutionError("Exception occurred: ${e.message}")
                        replayLog.executionResult?.testSteps?.add(currentReplayStep)
                        throw e
                    }
                }

                if (currentCoroutineContext().isActive) {
                    if(stepIndex >= (stepsToReplay.size - 1)) {
                        currentReplayStep.outcome = StepOutcome.CONTINUE
                    }
                    replayLog.executionResult?.testSteps?.add(currentReplayStep)
                    emit(replayLog)
                }
            }

            // --- Final Emission ---
            if (currentCoroutineContext().isActive) {
                val stepNumber = (replayLog.executionResult?.testSteps?.size ?: 0) + 1

                val mcpResponse = makeMCPCall(replayLog, deviceId, 2, model)
                mcpResponse.title = "Step $stepNumber: Verification of Test"
                replayLog.executionResult?.testSteps?.add(mcpResponse)
                replayLog.status = when(mcpResponse.outcome) {
                    StepOutcome.SUCCESS -> TestStatus.PASSED
                    StepOutcome.FAILURE -> TestStatus.FAILED
                    StepOutcome.CONTINUE -> TestStatus.RUNNING
                    StepOutcome.ERROR -> {
                        val errorMessage = mcpResponse.errorMessage ?: "Error while processing step: ${mcpResponse.title}"
                        replayLog.error = ExecutionError(errorMessage)
                        TestStatus.FAILED
                    }
                }
                replayLog.endTime = System.currentTimeMillis()

                emit(replayLog.copy())
                log.info("Emitted step $stepNumber. FinalStatus: ${replayLog.status}\n\n")
            }
        } catch (e: CancellationException) {
            replayLog.status = TestStatus.STOPPED
            replayLog.error = ExecutionError("Replay Test stopped by User.")
        } catch (e: Exception) {
            replayLog.status = TestStatus.STOPPED
            replayLog.error = ExecutionError("Replay failed: ${e.message}")
        } finally {
            replayLog.endTime = System.currentTimeMillis()
            emit(replayLog)
        }
    }.flowOn(Dispatchers.IO)

