interface TestCaseRepository {
    var isTestRunning: Boolean

    fun runTestCase(testId: String, textInput: String, deviceId: String, model: AiModelData): Flow<TestExecutionLog>

    suspend fun stopRunningTest()

    /**
     * Provides a Flow that emits the current list of connected ADB devices
     * whenever the list changes. The flow handles the underlying ADB listener.
     * Emits an empty list if ADB is unavailable or an error occurs during fetch.
     */
    fun getAdbDevicesFlow(): Flow<List<IDevice>>

    /**
     * Saves the details of a completed test execution log using the persistence service.
     * @param logData The complete log data to save.
     * @return A Result containing the path (String) to the saved file on success,
     * or an Exception on failure.
     */
    suspend fun saveExecutionLog(logData: TestExecutionLog): Result<String>

    /**
     * Loads all previously saved test execution logs for the current project.
     * @return A Result containing the List of logs on success, or an Exception on failure.
     */
    suspend fun loadExecutionLogs(): Result<List<TestExecutionLog>> // Added load method

    /**
     * Replays a given list of test steps by executing the tool calls found within them.
     * Emits the state of the replay's own TestExecutionLog as it progresses.
     *
     * @param replayLogId A unique ID generated by the caller for this specific replay attempt.
     * @param deviceId The target device ID for replay.
     * @param originalLog The original TestExecutionLog containing the steps to replay.
     * @return A Flow emitting TestExecutionLog objects reflecting the state of the replay attempt.
     */
    suspend fun replayTestSteps(replayLogId: String, deviceId: String, originalLog: TestExecutionLog, model: AiModelData): Flow<TestExecutionLog>

    fun testFun(deviceId: String)
}

